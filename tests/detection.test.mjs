test('report invariants hold for a range of accounts', () => {
  const accounts = [
    makeTweet(),
    makeTweet({ is_blue_verified: true }),
    makeTweet({
      screen_name: 'bot123456',
      description: '',
      profile_banner_url: '',
    }),
    makeTweet({ created_at: new Date(fixedNow - 5 * dayMs).toISOString() }),
    makeTweet({ followers_count: 5, friends_count: 500 }),
    makeTweet(
      { description: 'my onlyfans', is_blue_verified: true },
      { verified: true }
    ),
    makeTweet({ created_at: 'garbage', followers_count: undefined }),
  ];

  for (const tweet of accounts) {
    const report = getReport(tweet);
    const sum = report.checks.reduce(
      (total, item) => total + item.contribution,
      0
    );

    for (const item of report.checks) {
      assert.equal(
        item.contribution,
        item.triggered ? item.weight : 0,
        item.id
      );
    }
    assert.equal(report.chance, Math.min(sum, 1));
    assert.ok(report.chance >= 0 && report.chance <= 1);
    assert.equal(report.isBot, report.chance >= report.isBotThreshold);
    assert.equal(
      new Set(report.checks.map((item) => item.id)).size,
      report.checks.length
    );
  }
});

test('an account with many red flags is capped at 100% and marked as a bot', () => {
  const report = getReport(
    makeTweet({
      is_blue_verified: true,
      created_at: new Date(fixedNow - 10 * dayMs).toISOString(),
      statuses_count: 5000,
      followers_count: 5,
      friends_count: 500,
      screen_name: 'bot123456',
      description: '',
      profile_banner_url: '',
    })
  );

  const sum = report.checks.reduce(
    (total, item) => total + item.contribution,
    0
  );
  assert.ok(sum > 1, 'the raw sum should exceed 1 so the cap is exercised');
  assert.equal(report.chance, 1);
  assert.equal(report.isBot, true);
});

