  lopsidedFollowing: 0.1,
  lowFollowerFollowingRatio: 0.1, // bot-nets follow and like each other
  defaultProfileImage: 0.1,
  displayNameSpam: 0.1,
  scamKeywordsBio: 0.1,
  duplicateText: 0.1,
  engagementMismatch: 0.08,
  quotedCheckmark: 0.05, // people get rage-baited, so lower
  postAiAccount: 0.05,
  noDescription: 0.05,
  noBanner: 0.05,
  randomHandle: 0.05,
