// region weights

/**
 * Weights for each check.
 * TODO: make sure these add up to 1 (or adjust BOT_THRESHOLD accordingly)
 */
const WEIGHTS = {
  blueCheck: 0.4, // Blue checks aren't worth anything anymore.
  onlyFansModel: 0.2, // why is it always onlyfans accounts
  newAccount: 0.15,
  highTweetRate: 0.15,
  autoGeneratedHandle: 0.15,
  lowFollowersRatio: 0.1,
  excessivePromo: 0.1, // accounts that excessively promote content in their profile
  lowFollowerFollowingRatio: 0.1, // bot-nets follow and like each other
  quotedCheckmark: 0.05, // people get rage-baited, so lower
  postAiAccount: 0.05,
  noDescription: 0.05,
  noBanner: 0.05,
  aiCharactersBio: 0.05, // weak signal on its own, plenty of humans use smart punctuation
  accountCreationDate: 0.03, // strange and potentially indicative of bot behavior, but not conclusive whatsoever
} as const;
type Weights = Record<keyof typeof WEIGHTS, number>;

/**
 * TODO: probably too strict
 * @param user
 * @returns True if a user is a "professional" of type Business or has a verified type of Business.
 */
function isBusiness(user: Tweet['user'] | undefined): boolean {
  return (
    (!!user?.professional &&
      user.professional.professional_type === 'Business') ||
    user?.verified_type === 'Business'
  );
}

/**
 * @returns True if the user's verification is organizational (Business or Government) rather than a paid blue check.
 */
function isOfficialVerification(user: Tweet['user'] | undefined): boolean {
  return isBusiness(user) || user?.verified_type === 'Government';
}

const KNOWN_ONLYFANS_LINKS = ['onlyfans.com', 'fansly.com', 'spicey.link'];
const LEET_MAP: Record<string, string> = {
  '0': 'o',
  '1': 'l',
  '3': 'e',
  '4': 'a',
  '5': 's',
  $: 's',
  '@': 'a',
};

/**
 * Detects OnlyFans-style promotion in a profile: the keyword (including leetspeak),
 * "OF: link" patterns, known links, or the 👉 emoji in the location field.
 */
function looksLikeOnlyFans(user: Tweet['user']): boolean {
  const description = user.description ?? '';
  const text = `${description} ${user.name ?? ''}`;
  const deLeeted = text.replace(/[01345$@]/g, (char) => LEET_MAP[char] ?? char);
  const lower = text.toLowerCase();

  return (
    /onlyfans/i.test(deLeeted) ||
    /\bof\s*:\s*(https?:\/\/|\S+\.\S+)/i.test(text) ||
    KNOWN_ONLYFANS_LINKS.some((link) => lower.includes(link))
  );
}

function looksLikeExcessivePromo(user: Tweet['user']): boolean {
  const description = user.description ?? '';
  const text = `${description} ${user.name ?? ''}`;
  const lower = text.toLowerCase();

  return (user.location ?? '').includes('👉');
}

const AI_CHARACTERS = /[—–…‘’“”→←↑↓]/;

/**
 * Creates a check for the bot detection report.
 * @param id The unique identifier for the check.
 * @param label The human-readable label for the check.
 * @param weight The weight of the check in the overall bot detection score.
 * @param triggered Whether the check was triggered.
 * @returns A BotCheck object representing the result of the check.
 */
function makeCheck(
  id: string,
  label: string,
  weight: number,
  triggered: boolean
): BotCheck {
  return {
    id,
    label,
    weight,
    triggered,
    contribution: triggered ? weight : 0,
  };
}

function isAccountCreationOnFirstOrLastDay(user: Tweet['user']): boolean {
  return isFirstOrLastDayOfMonth(new Date(user.created_at));
}

interface GetDetectionReportOptions {
  weights: Weights;
  isBotThreshold: number;
  dayMs: number;
}

export const DEFAULT_DETECTION_REPORT_OPTIONS: GetDetectionReportOptions = {
  weights: WEIGHTS,
  isBotThreshold: 0.75, // arbitrary for now
  dayMs: 24 * 60 * 60 * 1000, // number of milliseconds in a day
};

/**
 *
 * TODO: consider perhaps using a "no-trust" approach? Where everyone starts at 100 and evidence reduces the score?
 * @param tweet The tweet to analyze for bot detection.
 * @param weights The weights to use for each bot check.
 * @returns A bot detection report if the tweet could be analyzed, otherwise undefined.
 */
export function getDetectionReport(
  tweet: Tweet | undefined,
  options:
    GetDetectionReportOptions | undefined = DEFAULT_DETECTION_REPORT_OPTIONS
): BotDetectionReport | undefined {
  if (!tweet) return;

  const { weights, isBotThreshold, dayMs } = options;

  const user = tweet.user;
  const quotedUser = tweet.quoted_status?.user;

  const isVerified = (user.verified || user.is_blue_verified) ?? false;
  const isVerifiedBusiness = isBusiness(user);
  const isQuotedUserVerified =
    (quotedUser?.verified || quotedUser?.is_blue_verified) ?? false;
  const isQuotedUserBusiness = isBusiness(quotedUser);
  const quotedUserVerifiedType = quotedUser?.verified_type;
  const didQuoteCheckmark =
    isQuotedUserVerified && !quotedUserVerifiedType && !isQuotedUserBusiness;

  const createdMs = Date.parse(user.created_at);
  const ageDays = Number.isNaN(createdMs)
    ? undefined
    : Math.max((Date.now() - createdMs) / dayMs, 1);
  const tweetsPerDay =
    ageDays !== undefined ? (user.statuses_count ?? 0) / ageDays : 0;
  const followers = user.followers_count ?? 0;
  const following = user.friends_count ?? 0;

  // region checks
  const checks: BotCheck[] = [
    makeCheck(
      'blue-check',
      'Paid blue checkmark (non-business)',
      weights.blueCheck,
      isVerified && !isOfficialVerification(user)
    ),
    makeCheck(
      'quoted-checkmark',
      'Quote-tweeted a blue checkmark',
      weights.quotedCheckmark,
      didQuoteCheckmark
    ),
    makeCheck(
      'new-account',
      'Account younger than 90 days',
      weights.newAccount,
      ageDays !== undefined && ageDays < 90
    ),
    makeCheck(
      'post-ai-account',
      'Account was created after 2023-01-01',
      weights.postAiAccount,
      ageDays !== undefined &&
        new Date(user.created_at) > new Date('2023-01-01')
    ),
    makeCheck(
      'account-creation-date',
      'Account created on the first or last day of the month',
      weights.accountCreationDate,
      ageDays !== undefined && isAccountCreationOnFirstOrLastDay(user)
    ),
    makeCheck(
      'high-tweet-rate',
      'More than 100 posts per day on average',
      weights.highTweetRate,
      tweetsPerDay > 100
    ),
    makeCheck(
      'low-followers-ratio',
      'Follows many more accounts than follow it',
      weights.lowFollowersRatio,
      following >= 100 && followers / following < 0.1
    ),
    makeCheck(
      'low-followers-following-ratio',
      'Bot accounts follow each other and like each others posts. Having around the same amount of followers and following is a common pattern.',
      weights.lowFollowerFollowingRatio,
      following >= 100 &&
        followers / following >= 0.9 &&
        followers / following <= 1.1
    ),
    makeCheck(
      'auto-handle',
      'Handle ends in 4+ digits (auto-generated)',
      weights.autoGeneratedHandle,
      /\d{5,}$/.test(user.screen_name ?? '')
    ),
    makeCheck(
      'onlyfans-model',
      "OnlyFans accounts automatically get flagged. It's always them.",
      weights.onlyFansModel,
      looksLikeOnlyFans(user)
    ),
    makeCheck(
      'excessive-promo',
      'Accounts that excessively promote content in their profile.',
      weights.excessivePromo,
      looksLikeExcessivePromo(user)
    ),
    makeCheck(
      'ai-characters-bio',
      'Bio contains typographic characters (em dash, ellipsis, curly quotes, arrows) rarely typed by hand',
      weights.aiCharactersBio,
      AI_CHARACTERS.test(user.description ?? '')
    ),
    makeCheck(
      'no-description',
      'Empty profile description/bio',
      weights.noDescription,
      !user.description?.trim()
    ),
    makeCheck(
      'no-banner',
      'No profile banner',
      weights.noBanner,
      !user.profile_banner_url
    ),
  ];

  const chance = Math.min(
    checks.reduce((sum, c) => sum + c.contribution, 0),
    1
  );

  return {
    chance,
    checks,
    isVerified,
    verifiedType: user.verified_type,
    isVerifiedBusiness,
    isQuotedUserVerified,
    isQuotedUserBusiness,
    quotedUserVerifiedType,
    didQuoteCheckmark,
    isBot: chance >= isBotThreshold,
    isBotThreshold: isBotThreshold,
  };
}
